"""Generate the companion computer's service files for a Raspberry Pi image.

Prototype layout (Raspberry Pi OS Lite):
  /etc/sentinel/companion.json      relay endpoints, policy, video URL (no secrets)
  /var/lib/sentinel/identity.json   companion id + secret (0600, written by `pair`)
  /etc/mediamtx.yml                 camera -> RTSP (Pi camera via rpicam, or the gimbal camera's own RTSP)
  sentinel-companion.service        relay + health agent (systemd)

Nothing here contains a password: the RTSP read password is generated at
provisioning time and entered once in the Hub, which keeps it in its
credential store."""

from __future__ import annotations

import json
import secrets
from typing import Any


def companion_config(*, fc: str, hub_host: str, hub_port: int = 14551, gcs: list[str] | None = None, video_url: str = "") -> dict[str, Any]:
    return {"fc": fc, "hub": f"udp:{hub_host}:{hub_port}", "gcs": gcs or ["udp:0.0.0.0:14550"], "policy": "telemetry",
            "video_url": video_url, "identity": "/var/lib/sentinel/identity.json"}


def mediamtx_config(*, camera: str = "rpi", upstream_rtsp: str = "", read_user: str = "sentinel", read_password: str | None = None,
                    width: int = 1280, height: int = 720, fps: int = 15, bitrate: int = 2_500_000) -> tuple[str, str]:
    """(yaml text, generated read password). `camera` is "rpi" (CSI camera, hardware
    H.264 on Zero 2 W / CM4) or "rtsp" (relay a gimbal camera's stream unchanged)."""
    password = read_password or secrets.token_urlsafe(18)
    if camera == "rpi":
        source = (f"    source: rpiCamera\n    rpiCameraWidth: {width}\n    rpiCameraHeight: {height}\n"
                  f"    rpiCameraFPS: {fps}\n    rpiCameraBitrate: {bitrate}\n")
    elif camera == "rtsp" and upstream_rtsp:
        source = f"    source: {upstream_rtsp}\n    sourceOnDemand: yes\n    rtspTransport: tcp\n"
    else:
        raise ValueError("camera must be 'rpi' or 'rtsp' with an upstream URL")
    text = ("# Generated by sentinel.companion.provision\nrtspAddress: :8554\nwebrtc: no\nhls: no\nsrt: no\nrtmp: no\n"
            "authInternalUsers:\n"
            f"  - user: {read_user}\n    pass: {password}\n    ips: []\n    permissions:\n      - action: read\n        path: drone\n"
            "  - user: any\n    pass:\n    ips: ['127.0.0.1', '::1']\n    permissions:\n      - action: publish\n        path: drone\n"
            f"paths:\n  drone:\n{source}")
    return text, password


def systemd_unit(python: str = "/usr/bin/python3", config: str = "/etc/sentinel/companion.json") -> str:
    return f"""[Unit]
Description=Sentinel drone companion (MAVLink relay and health agent)
After=network-online.target
Wants=network-online.target

[Service]
ExecStart={python} -m sentinel.companion run --config {config}
Restart=always
RestartSec=2
User=sentinel
NoNewPrivileges=yes
ProtectSystem=strict
ReadWritePaths=/var/lib/sentinel
PrivateTmp=yes

[Install]
WantedBy=multi-user.target
"""


def write_bundle(directory: str, **kwargs: Any) -> dict[str, str]:
    """Write all three files into `directory` (for copying onto the image)."""
    from pathlib import Path

    target = Path(directory)
    target.mkdir(parents=True, exist_ok=True)
    camera = kwargs.pop("camera", "rpi")
    upstream = kwargs.pop("upstream_rtsp", "")
    yaml_text, password = mediamtx_config(camera=camera, upstream_rtsp=upstream)
    (target / "companion.json").write_text(json.dumps(companion_config(**kwargs), indent=2))
    (target / "mediamtx.yml").write_text(yaml_text)
    (target / "sentinel-companion.service").write_text(systemd_unit())
    return {"directory": str(target), "rtsp_read_user": "sentinel", "rtsp_read_password": password}
